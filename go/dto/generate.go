package dto

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
	"unicode"

	"github.com/montionugera/node-server-decorator/v2/go/entity"
)

// GenerateGoStructs generates Go struct code for create, update, read, and action DTOs of an EntitySpec.
func GenerateGoStructs(spec entity.Spec, packageName string) ([]byte, error) {
	if packageName == "" {
		packageName = "dto"
	}

	entityName := Capitalize(spec.Entity)
	definedStructs := make(map[string]string)

	// Nested obj structs are named after the owning DTO (UserCreateProfile, UserReadProfile):
	// each DTO kind filters nested members with its own include rule, so they cannot share one.
	var body bytes.Buffer

	// 1. Create DTO
	err := writeStruct(&body, entityName+"CreateDTO", spec.Fields, notReadonly, false, entityName+"Create", definedStructs)

	// 2. Update DTO (top-level optional for partial updates)
	if err == nil {
		err = writeStruct(&body, entityName+"UpdateDTO", spec.Fields, notReadonly, true, entityName+"Update", definedStructs)
	}

	// 3. Read DTO
	if err == nil {
		err = writeStruct(&body, entityName+"ReadDTO", spec.Fields, notWriteonly, false, entityName+"Read", definedStructs)
	}

	// 4. Action DTOs
	for _, act := range spec.Actions {
		if err != nil {
			break
		}
		actName := Capitalize(act.Name)
		err = writeStruct(&body, entityName+"Action"+actName+"DTO", act.Input, includeAll, false, entityName+"Action"+actName, definedStructs)
	}
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gen-dto. DO NOT EDIT.\n")
	buf.WriteString(fmt.Sprintf("package %s\n\n", packageName))
	// Only a kept datetime field (at any depth) emits time.Time; an unconditional import does
	// not compile for a datetime-free spec.
	if bytes.Contains(body.Bytes(), []byte("time.Time")) {
		buf.WriteString("import (\n\t\"time\"\n)\n\n")
	}
	buf.Write(body.Bytes())

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), fmt.Errorf("failed to format generated Go code: %w\n%s", err, buf.String())
	}
	return formatted, nil
}

// Capitalize capitalizes the first rune of a string.
func Capitalize(s string) string {
	if len(s) == 0 {
		return ""
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// writeStruct appends structName and its nested structs to out. definedStructs maps every
// emitted struct name to its source: a second struct with the same name and a different shape
// is an error, never a silent first-writer-wins.
func writeStruct(out *bytes.Buffer, structName string, fields []entity.Field, include includePredicate, forceOptional bool, prefix string, definedStructs map[string]string) error {
	filtered := filterFields(fields, include)
	buf := &bytes.Buffer{}
	buf.WriteString(fmt.Sprintf("type %s struct {\n", structName))

	var nestedStructs []struct {
		name   string
		fields []entity.Field
		prefix string
	}

	seenFields := make(map[string]string, len(filtered))
	for _, f := range filtered {
		goFieldName := Capitalize(f.Name)
		if prevWire, exists := seenFields[goFieldName]; exists {
			return fmt.Errorf("struct %s has duplicate Go field name %s from fields %s and %s", structName, goFieldName, prevWire, f.Name)
		}
		seenFields[goFieldName] = f.Name

		isOptional := forceOptional || f.Optional

		goType, nested := goTypeForField(f, isOptional, include, prefix+goFieldName)
		if nested != nil {
			nestedStructs = append(nestedStructs, *nested)
		}

		jsonTag := f.Name
		if isOptional {
			jsonTag += ",omitempty"
		}

		var bindingRules []string
		if isOptional {
			bindingRules = append(bindingRules, "omitempty")
		} else {
			bindingRules = append(bindingRules, "required")
			if f.Format != "" {
				bindingRules = append(bindingRules, f.Format)
			}
		}
		bindingTag := strings.Join(bindingRules, ",")

		buf.WriteString(fmt.Sprintf("\t%s %s `json:\"%s\" binding:\"%s\"`\n", goFieldName, goType, jsonTag, bindingTag))
	}

	buf.WriteString("}\n\n")

	if prev, exists := definedStructs[structName]; exists {
		if prev != buf.String() {
			return fmt.Errorf("generated struct name %s is produced by two different shapes; rename one of the fields or actions that map to it", structName)
		}
	} else {
		definedStructs[structName] = buf.String()
		out.Write(buf.Bytes())
	}

	for _, ns := range nestedStructs {
		if err := writeStruct(out, ns.name, ns.fields, include, false, ns.prefix, definedStructs); err != nil {
			return err
		}
	}
	return nil
}

type nestedDef struct {
	name   string
	fields []entity.Field
	prefix string
}

func goTypeForField(f entity.Field, isOptional bool, include includePredicate, contextName string) (string, *nestedDef) {
	var baseType string
	var nested *nestedDef

	switch f.Type {
	case "str", "ref":
		baseType = "string"
	case "int":
		baseType = "int"
	case "float":
		baseType = "float64"
	case "bool":
		baseType = "bool"
	case "datetime":
		baseType = "time.Time"
	case "enum":
		baseType = "string"
	case "list":
		if f.Item != nil {
			itemType, itemNested := goTypeForField(*f.Item, false, include, contextName+"Item")
			baseType = "[]" + itemType
			nested = itemNested
		} else {
			baseType = "[]any"
		}
	case "obj":
		nestedName := contextName
		nested = &nestedDef{
			name:   nestedName,
			fields: f.Fields,
			prefix: nestedName,
		}
		baseType = nestedName
	default:
		baseType = "any"
	}

	// In Go, nullable or optional fields are usually represented as pointers if they are scalar or struct
	if (isOptional || f.Nullable) && !strings.HasPrefix(baseType, "[]") {
		baseType = "*" + baseType
	}

	return baseType, nested
}
